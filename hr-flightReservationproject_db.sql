--AIRLINE_GRADE_FUNC
CREATE OR REPLACE FUNCTION AIRLINE_GRADE_FUNC(VNO IN AIRLINE.NO%TYPE)RETURN VARCHAR2
IS
    VNAME VARCHAR2(30);
    VGRADE VARCHAR2(10);
    VMESSAGE VARCHAR2(200);
BEGIN
    SELECT NAME,GRADE INTO VNAME, VGRADE FROM AIRLINE WHERE NO = VNO;
    VMESSAGE := '항공사 이름은 '||VNAME||'이고 항공사등급은 '||VGRADE||'입니다.';
    RETURN VMESSAGE;
END;
