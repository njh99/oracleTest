--CUSTOMER 백업 테이블
CREATE TABLE CUSTOMER_RECYCLEBIN(
    NUM NUMBER(3),
    ID VARCHAR2(20),
    PASSWD VARCHAR2(20),
    NAME VARCHAR2(20),
    PASSPORT_NUMBER VARCHAR2(30),
    MILEAGE NUMBER(10)
);
--AIRLINE 백업 테이블
CREATE TABLE AIRLINE_RECYCLEBIN(
    NO NUMBER(10),
    NAME VARCHAR2(30) NOT NULL,
    ENGLISH_NAME  VARCHAR2(30) NOT NULL,
    COUNTRY VARCHAR2(30) NOT NULL,
    GRADE VARCHAR2(10)
);
--AIRLINE_RECYCLEBIN 시퀀스
CREATE SEQUENCE AIRLINE_RECYCLEBIN_SEQ
START WITH 1
INCREMENT BY 1;

--AIRLINE DELETE TRIGGER
CREATE OR REPLACE TRIGGER AIRLINE_RECYCLEBIN_TRIGGER
    BEFORE DELETE ON AIRLINE
    FOR EACH ROW
BEGIN
    INSERT INTO AIRLINE_RECYCLEBIN VALUES(AIRLINE_RECYCLEBIN_SEQ.NEXTVAL, :OLD.NAME,:OLD.ENGLISH_NAME, :OLD.COUNTRY, :OLD.GRADE);
END;
/



